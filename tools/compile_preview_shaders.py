#!/usr/bin/env python3
"""Explicitly regenerate the embedded UV shader bytecode (requires the pinned DXC SDK)."""
import argparse
from pathlib import Path
import struct
import subprocess


def main():
    root = Path(__file__).resolve().parent.parent
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--dxc', type=Path, default=root / 'external/RadRay/SDKs/radray_dxc/extracted/bin/dxc.exe')
    args = parser.parse_args()
    output = root / 'build/preview-shaders'
    output.mkdir(parents=True, exist_ok=True)
    lines = ['// Generated by tools/compile_preview_shaders.py; edit native/shaders/uv.hlsl.',
             '#pragma once', '#include <cstddef>', '#include <cstdint>', '#include <span>', 'namespace raynium {']
    for stage, profile in [('Vs', 'vs_6_0'), ('Ps', 'ps_6_0')]:
        for kind, flags in [('Dxil', ['-Qstrip_rootsignature']),
                            ('Spirv', ['-spirv', '-fspv-target-env=vulkan1.2', '-fvk-use-dx-layout'])]:
            target = output / f'uv.{stage}.{kind}.bin'
            subprocess.run([str(args.dxc), '-I', str(root / 'external/RadRay/shaderlib'),
                            '-E', stage.upper() + 'Main', '-T', profile, '-O3', *flags,
                            '-Fo', str(target), str(root / 'native/shaders/uv.hlsl')], check=True)
            data = target.read_bytes()
            words = struct.unpack(f'<{len(data) // 4}I', data)
            lines += [f'inline std::span<const std::byte> Uv{stage}{kind}() noexcept {{',
                      '    static constexpr uint32_t data[]{']
            for i in range(0, len(words), 8):
                lines.append('        ' + ', '.join(f'0x{x:08x}u' for x in words[i:i+8]) + ',')
            lines += ['    };', '    return std::as_bytes(std::span{data});', '}']
    lines += ['}', '']
    (root / 'native/include/raynium/uv_bytecode.h').write_text('\n'.join(lines), encoding='utf-8')


if __name__ == '__main__':
    main()
