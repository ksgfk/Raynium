"""Freeze vanilla built-in post-chain wiring and std140 constants for native preparation."""
import argparse
import json
from pathlib import Path


def pack_constants(uniforms):
    result=[0.0]*64
    cursor=0
    for uniform in uniforms:
        kind=uniform['type']
        count={'float':1,'vec2':2,'vec3':3,'vec4':4}.get(kind)
        if count is None:
            raise ValueError('Unsupported post constant type: '+kind)
        alignment=4 if count>=3 else count
        cursor=(cursor+alignment-1)//alignment*alignment
        values=uniform['value'] if isinstance(uniform['value'],list) else [uniform['value']]
        if len(values)!=count or cursor+count>64:
            raise ValueError('Invalid post constant size')
        result[cursor:cursor+count]=values
        cursor+=count
    return result


def generate(interfaces,chains):
    programs={item['id']:item for item in interfaces}
    lines=['// Generated by tools/generate_post_catalog.py from vanilla built-in post effects.',
        'bool DescribePostPipeline(uint32_t id,ScenePipelineDescription& result) {','    switch(id) {']
    for item in interfaces:
        cb=sum(1<<slot['binding'] for slot in item['constants'].values())
        textures=sum(1<<slot['texture'] for slot in item['textures'].values())
        lines += [f'    case {item["id"]}: result.program="{item["program"]}"; result.declaredBindings={{{cb}ull,{textures}ull}}; break;']
    lines += ['    default: return false;','    }','    result.screen=true; result.primitive.Cull=CullMode::None;',
        '    result.colors.push_back(ColorTargetState::Default(TextureFormat::RGBA8_UNORM));','    return true;','}']
    for chain in chains:
        targets={name:index+1 for index,name in enumerate(chain['targets'])}
        external='minecraft:entity_outline' if chain['name']=='entity_outline' else 'minecraft:main'
        targets[external]=0
        if any(value for value in chain['targets'].values()):
            raise ValueError('Unsupported built-in post target sizing')
        for index,item in enumerate(chain['passes']):
            program=programs[item['pipeline']]; name=f'Post{chain["id"]}_{index}'
            constants=[]
            for block,slot in program['constants'].items():
                kind=1 if block=='Globals' else 2 if block=='SamplerInfo' else 0
                values=pack_constants(item['uniforms'][block]) if kind==0 else [0]*64
                constants.append('{'+f'{slot["binding"]},{kind},'+'{'+','.join(f'{float(v)}f' for v in values)+'}}')
            lines += [f'static const radray::array<PostConstantDescription,{len(constants)}> {name}Constants{{{{'+','.join(constants)+'}};']
            inputs=[]
            for source in item['inputs']:
                binding=program['textures'][source['sampler_name']+'Sampler']['texture']
                if source.get('use_depth_buffer') or 'target' not in source:
                    raise ValueError('Unsupported built-in post input')
                inputs.append('{'+f'{binding},{targets[source["target"]]},{str(source.get("bilinear",False)).lower()}'+'}')
            lines += [f'static const radray::array<PostInputDescription,{len(inputs)}> {name}Inputs{{{{'+','.join(inputs)+'}};']
        passes=['{'+f'{item["pipeline"]},{targets[item["output"]]},Post{chain["id"]}_{i}Constants,Post{chain["id"]}_{i}Inputs'+'}' for i,item in enumerate(chain['passes'])]
        if chain['name']=='entity_outline':
            lines += ['static const radray::array<PostInputDescription,1> Post3CompositeInputs{{{0,0,false}}};']
            passes.append('{35,2,{},Post3CompositeInputs}')
        lines += [f'static const radray::array<PostPassDescription,{len(passes)}> Post{chain["id"]}Passes{{{{'+','.join(passes)+'}};']
    lines += ['bool DescribePostChain(uint32_t id,PostChainDescription& result) {','    switch(id) {']
    for chain in chains:
        target_count=len(chain['targets'])+1+(chain['name']=='entity_outline')
        lines += [f'    case {chain["id"]}: result={{{target_count},Post{chain["id"]}Passes}}; return true;']
    lines += ['    default: return false;','    }','}','']
    return '\n'.join(lines)


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--shaders',type=Path,required=True)
    parser.add_argument('--output',type=Path,required=True)
    args=parser.parse_args()
    interfaces=json.loads((args.shaders/'post-interfaces.json').read_text(encoding='utf-8'))
    chains=json.loads((args.shaders/'post-chains.json').read_text(encoding='utf-8'))
    args.output.write_text(generate(interfaces,chains),encoding='utf-8')


if __name__=='__main__': main()
