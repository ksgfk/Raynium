"""Generate native raster descriptions from the exported vanilla identities and converted interfaces."""
import argparse
import json
from pathlib import Path
import re

FORMATS = {'R32_FLOAT':'FLOAT32', 'RG16_SINT':'SINT16X2', 'RG32_FLOAT':'FLOAT32X2',
           'RGB32_FLOAT':'FLOAT32X3', 'RGB32_SINT':'SINT32X3', 'RGBA8_SNORM':'SNORM8X4', 'RGBA8_UNORM':'UNORM8X4'}
FACTORS = {'ZERO':'Zero','ONE':'One','SRC_COLOR':'Src','ONE_MINUS_SRC_COLOR':'OneMinusSrc',
           'SRC_ALPHA':'SrcAlpha','ONE_MINUS_SRC_ALPHA':'OneMinusSrcAlpha','DST_COLOR':'Dst',
           'ONE_MINUS_DST_COLOR':'OneMinusDst','DST_ALPHA':'DstAlpha','ONE_MINUS_DST_ALPHA':'OneMinusDstAlpha'}
TOPOLOGIES = {'TRIANGLES':0,'QUADS':1,'LINES':5,'TRIANGLE_STRIP':2,'TRIANGLE_FAN':3,'POINTS':4}

def generate(catalog, interfaces, shaders):
    interfaces = {item['id']:item for item in interfaces}
    lines = ['// Generated by tools/generate_scene_catalog.py from the locked Minecraft pipeline catalog.',
             'bool DescribeScenePipeline(uint32_t id,ScenePipelineDescription& result) {', '    switch(id) {']
    for entry in catalog:
        state = entry['identity']; interface = interfaces[entry['id']]
        if 'error' in interface:
            raise ValueError(f"Unconverted pipeline: {entry['names'][0]}")
        source = (shaders/(interface['program']+'.hlsl')).read_text(encoding='utf-8')
        interface['texels']={name:int(binding)*2 for name,binding in re.findall(r'Buffer<[^>]+> (\w+) : register\(t(\d+), space1\)',source)}
        vertex = source.split('namespace VertexStage {',1)[1].split('namespace PixelStage {',1)[0]
        match = re.search(r'struct SPIRV_Cross_Input\s*\{(.*?)\};', vertex, flags=re.S)
        semantics = {} if not match else {name:int(index) for name,index in re.findall(r'\w+\s+(\w+)\s*:\s*TEXCOORD(\d+)',match[1])}
        lines += [f"    case {entry['id']}: {{ // {entry['names'][0]}",f'        result.program="{interface["program"]}";',
                  f'        result.topology={TOPOLOGIES[state["topology"]]};',
                  f'        result.primitive.Cull=CullMode::{"Back" if state["cull"] else "None"};',
                  f'        result.primitive.Poly=PolygonMode::{"Line" if state["polygonMode"]=="WIREFRAME" else "Fill"};']
        constants=sum(1 << binding['binding'] for binding in interface['constants'].values())
        textures=sum(1 << binding['texture'] for binding in interface['textures'].values()) | sum(1 << binding for binding in interface['texels'].values())
        lines.append(f'        result.declaredBindings={{{constants}ull,{textures}ull}};')
        lines.append(f'        result.screen={str(not any(state["vertices"]) and "CloudInfo" not in interface["constants"]).lower()};')
        for slot,binding in enumerate(state['vertices']):
            if not binding: continue
            step = 'Instance' if binding['stepRate'] or state['topology']=='POINTS' else 'Vertex'
            lines.append(f'        result.vertices.push_back({{{slot},{binding["stride"]},VertexStepMode::{step}}});')
            for element in binding['elements']:
                if element['name'] not in semantics: continue
                lines.append(f'        result.attributes.push_back({{{slot},{element["offset"]},"TEXCOORD",{semantics[element["name"]]},VertexFormat::{FORMATS[element["format"]]},0}});')
        depth = state['depth']
        if depth:
            compare = {'GREATER_THAN_OR_EQUAL':'GreaterEqual','EQUAL':'Equal','ALWAYS_PASS':'Always'}[depth['depthTest']]
            lines += ['        result.depth=DepthStencilState::Default();', f'        result.depth->DepthCompare=CompareFunction::{compare};',
                      f'        result.depth->DepthWriteEnable={str(depth["writeDepth"]).lower()};',
                      f'        result.depth->DepthBias={{{int(depth["depthBiasConstant"])},{float(depth["depthBiasScaleFactor"])}f,0}};']
        # A pass which only writes depth has no color attachment in the native graph.
        colors = state['colors']
        if colors and all(color is not None and color['writeMask']==0 for color in colors): colors = []
        for color in colors:
            if color is None: raise ValueError('Sparse attachment layout')
            lines += [f'        result.colors.push_back(ColorTargetState::Default(TextureFormat::{color["format"]}));',
                      f'        result.colors.back().WriteMask=static_cast<ColorWrite>({color["writeMask"]});']
            if color['blendFunction']:
                parts = []
                for key in ('color','alpha'):
                    blend=color['blendFunction'][key]
                    parts.append('{BlendFactor::'+FACTORS[blend['sourceFactor']]+',BlendFactor::'+FACTORS[blend['destFactor']]+',BlendOperation::'+{'ADD':'Add','MAX':'Max','MIN':'Min','SUBTRACT':'Subtract','REVERSE_SUBTRACT':'ReverseSubtract'}[blend['op']]+'}')
                lines.append('        result.colors.back().Blend=BlendState{'+','.join(parts)+'};')
        lines += ['        return true;', '    }']
    lines += ['    default: return false;', '    }', '}', '']
    return '\n'.join(lines)

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--catalog',type=Path,required=True)
    parser.add_argument('--shaders',type=Path,required=True)
    parser.add_argument('--native',type=Path,required=True)
    parser.add_argument('--java-resource',type=Path,required=True)
    args=parser.parse_args()
    catalog=json.loads(args.catalog.read_text(encoding='utf-8'))
    interfaces=json.loads((args.shaders/'interfaces.json').read_text(encoding='utf-8'))
    args.native.parent.mkdir(parents=True,exist_ok=True)
    args.native.write_text(generate(catalog,interfaces,args.shaders),encoding='utf-8')
    args.java_resource.parent.mkdir(parents=True,exist_ok=True)
    args.java_resource.write_text(json.dumps(interfaces,separators=(',',':'))+'\n',encoding='utf-8')

if __name__=='__main__': main()
